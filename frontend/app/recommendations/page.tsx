"use client";
import { useEffect, useState } from "react";
import Sidebar from "@/components/Sidebar";
import { api } from "@/lib/api";

const C = { card: { background: "#111C2D", border: "1px solid #1e3050", borderRadius: 10, padding: 16, marginBottom: 12 } as React.CSSProperties };
const STRENGTH_COLOR: Record<string, string> = { STRONG: "#22C55E", MODERATE: "#F59E0B", INDICATIVE: "#64748b" };

export default function RecommendationsPage() {
  const [recs, setRecs] = useState<any[]>([]);
  const [station, setStation] = useState("");
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    setLoading(true);
    api.recommendations(station || undefined).then(r => { setRecs(r.recommendations || []); setLoading(false); }).catch(() => setLoading(false));
  }, [station]);

  const stations = Array.from(new Set(recs.map((r: any) => r.police_station).filter((s: string) => !s.startsWith("Ward:")))).sort();

  return (
    <div style={{ display: "flex", minHeight: "100vh", background: "#080D18" }}>
      <Sidebar />
      <main style={{ flex: 1, padding: 24, overflowY: "auto" }}>
        <h1 style={{ fontSize: 20, fontWeight: 700, color: "#e2e8f0", marginBottom: 4 }}>Safety Recommendations</h1>
        <div style={{ background: "#0a1520", border: "1px solid #22C55E", borderLeftWidth: 4, borderRadius: 6, padding: "10px 14px", marginBottom: 16, fontSize: 11, color: "#94A3B8" }}>
          Evidence-based recommendations generated by the Road Safety Recommendation Agent.
          All recommendations are linked to supporting observations and are advisory — not verified engineering assessments.
          Implementation requires review by qualified traffic engineering authorities.
        </div>

        <div style={{ display: "flex", gap: 10, marginBottom: 16 }}>
          <select value={station} onChange={e => setStation(e.target.value)}
            style={{ background: "#0D1524", border: "1px solid #1e3050", color: "#e2e8f0", borderRadius: 6, padding: "7px 10px", fontSize: 12 }}>
            <option value="">All Locations</option>
            {stations.map(s => <option key={s} value={s}>{s}</option>)}
          </select>
          <span style={{ color: "#64748b", fontSize: 12, padding: "7px 0" }}>{recs.length} recommendations</span>
        </div>

        {loading ? <div style={{ color: "#29C8E8" }}>Loading…</div> : recs.map((r: any) => (
          <div key={r.id || r.priority_rank} style={C.card}>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start", marginBottom: 8 }}>
              <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
                <span style={{ background: "#0D1524", border: "1px solid #1e3050", borderRadius: 4, padding: "2px 8px", fontSize: 11, color: "#94A3B8" }}>#{r.priority_rank}</span>
                <span style={{ fontSize: 13, fontWeight: 700, color: "#e2e8f0" }}>{r.recommendation_type}</span>
              </div>
              <span style={{ fontSize: 11, fontWeight: 600, color: STRENGTH_COLOR[r.evidence_strength] || "#64748b", border: `1px solid ${STRENGTH_COLOR[r.evidence_strength] || "#64748b"}`, borderRadius: 4, padding: "2px 8px" }}>
                {r.evidence_strength}
              </span>
            </div>
            <div style={{ fontSize: 12, color: "#64748b", marginBottom: 6 }}>
              📍 {r.police_station}
            </div>
            <div style={{ fontSize: 12, color: "#e2e8f0", lineHeight: 1.6, marginBottom: 8 }}>
              {r.recommendation_text}
            </div>
            <div style={{ background: "#0D1524", borderRadius: 6, padding: "8px 10px", marginBottom: 6 }}>
              <div style={{ fontSize: 11, color: "#F59E0B", fontWeight: 600, marginBottom: 4 }}>Supporting Evidence</div>
              <div style={{ fontSize: 11, color: "#94A3B8", lineHeight: 1.5 }}>{r.evidence_summary}</div>
            </div>
            <div style={{ display: "flex", gap: 12, flexWrap: "wrap" }}>
              <span style={{ fontSize: 11, color: "#64748b" }}>Authority: <span style={{ color: "#94A3B8" }}>{r.responsible_authority}</span></span>
            </div>
            {r.data_limitations && (
              <div style={{ fontSize: 10, color: "#475569", marginTop: 6, fontStyle: "italic" }}>
                ⚠ {r.data_limitations}
              </div>
            )}
          </div>
        ))}
      </main>
    </div>
  );
}
